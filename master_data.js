// 5. EXERCISE EXP ENGINE (ACUMULACIÓN DE EXPERIENCIA EN ESTADO GLOBAL)
// --------------------------------------------------------------------------
window.EXERCISE_EXP_ENGINE = (function() {
  const STORAGE_KEY = 'english_app_exercise_stats';
  let stats = {
    totalExpEarned: 0,
    totalCorrect: 0,
    totalAttempts: 0,
    currentStreak: 0,
    bestStreak: 0
  };

  function loadStats() {
    if (typeof localStorage === 'undefined') return;
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (raw) stats = Object.assign(stats, JSON.parse(raw));
    } catch (e) {}
  }

  function saveStats() {
    if (typeof localStorage === 'undefined') return;
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(stats));
    } catch (e) {}
  }

  loadStats();

  /**
   * Vincula las respuestas correctas de los ejercicios con la acumulación de experiencia (+EXP)
   * en el estado global, calculando bonos de racha y actualizando el perfil de usuario.
   */
  function awardExerciseExp(type, isCorrect, options = {}) {
    stats.totalAttempts++;

    const baseRewards = {
      'roulette': 15,
      'mission': 20,
      'story_vocab': 25,
      'music_challenge': 30,
      'toefl_question': 50,
      'general_quiz': 15
    };

    const expAmount = options.expAmount || baseRewards[type] || 15;
    const reason = options.reason || `Respuesta en ${type}`;

    if (isCorrect) {
      stats.currentStreak++;
      stats.totalCorrect++;
      if (stats.currentStreak > stats.bestStreak) {
        stats.bestStreak = stats.currentStreak;
      }

      // Bono por racha consecutiva: +5 EXP cada 3 aciertos seguidos
      let streakBonus = 0;
      if (stats.currentStreak >= 3 && stats.currentStreak % 3 === 0) {
        streakBonus = 5;
      }
      const totalAward = expAmount + streakBonus;
      stats.totalExpEarned += totalAward;
      saveStats();

      // 1. Invocar la función global addExp si existe en la aplicación
      if (typeof window.addExp === 'function') {
        const fullReason = streakBonus > 0
          ? `${reason} (¡Racha x${stats.currentStreak}! +${streakBonus} EXP extra)`
          : reason;
        window.addExp(totalAward, fullReason);
      } else {
        // Fallback directo a localStorage para garantizar persistencia de EXP
        try {
          const userRaw = localStorage.getItem('english_app_user');
          if (userRaw) {
            const user = JSON.parse(userRaw);
            user.exp = (parseInt(user.exp, 10) || 0) + totalAward;
            localStorage.setItem('english_app_user', JSON.stringify(user));
          }
        } catch (e) {}
      }

      // 2. Disparar evento personalizado en el DOM para reactividad de interfaz
      if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
        try {
          window.dispatchEvent(new CustomEvent('english:exercise-completed', {
            detail: {
              type: type,
              isCorrect: true,
              awardedExp: totalAward,
              streak: stats.currentStreak,
              bestStreak: stats.bestStreak
            }
          }));
        } catch (e) {}
      }

      return {
        isCorrect: true,
        awardedExp: totalAward,
        streak: stats.currentStreak,
        streakBonus: streakBonus
      };
    } else {
      // Reiniciar racha en respuesta incorrecta
      stats.currentStreak = 0;
      saveStats();

      if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
        try {
          window.dispatchEvent(new CustomEvent('english:exercise-completed', {
            detail: {
              type: type,
              isCorrect: false,
              streak: 0
            }
          }));
        } catch (e) {}
      }

      return {
        isCorrect: false,
        awardedExp: 0,
        streak: 0,
        streakBonus: 0
      };
    }
  }

  return {
    awardExerciseExp: awardExerciseExp,

    /**
     * Valida de manera limpia una respuesta de ejercicio y acumula el EXP correspondiente
     */
    checkAndAward: function(selectedIdx, correctIdx, type = 'general_quiz', options = {}) {
      const isCorrect = (selectedIdx === correctIdx);
      return awardExerciseExp(type, isCorrect, options);
    },

    getStats: function() {
      return Object.assign({}, stats);
    },

    resetStreak: function() {
      stats.currentStreak = 0;
      saveStats();
    }
  };
})();

// Inicialización de auto-delegación una vez que el DOM esté listo
if (typeof window !== 'undefined') {
  function initMasterDataRuntime() {
    // Escuchar clics en palabras clave con clase .karaoke-keyword
    document.addEventListener('click', function(e) {
      const target = e.target.closest('.karaoke-keyword, [data-vocab-term]');
      if (target && window.VOCAB_TOOLTIP_ENGINE) {
        window.VOCAB_TOOLTIP_ENGINE.show(e, target, target.dataset.vocabTerm || target.textContent);
      }
    });

    // Auto-detección de reproductores <audio> presentes en el DOM
    const audioTags = document.querySelectorAll('audio');
    audioTags.forEach(a => {
      window.KARAOKE_SYNC_ENGINE.attachAudioPlayer(a);
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initMasterDataRuntime);
  } else {
    initMasterDataRuntime();
  }
}
