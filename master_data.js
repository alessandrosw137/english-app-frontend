// 3. KARAOKE SYNC & AUDIO 'TIMEUPDATE' ENGINE (SMOOTH CENTERED SCROLL)
// --------------------------------------------------------------------------
window.KARAOKE_SYNC_ENGINE = (function() {
  let attachedPlayer = null;
  let activeTrackData = null;
  let activeLyricsContainer = null;
  let currentActiveIndex = -1;
  let isSyncActive = false;
  let isUserScrolling = false;
  let userScrollTimeout = null;
  const subscribers = [];

  function getContainer() {
    if (activeLyricsContainer && document.body.contains(activeLyricsContainer)) {
      return activeLyricsContainer;
    }
    const musicContainer = document.getElementById('musicLyricsContainer');
    if (musicContainer) return musicContainer;
    const storiesContainer = document.getElementById('storyParagraphsContainer');
    if (storiesContainer) return storiesContainer;
    return null;
  }

  function monitorUserScrollInteractions(container) {
    if (!container || container._hasSyncMonitorAttached) return;
    container._hasSyncMonitorAttached = true;

    const onUserTouch = () => {
      isUserScrolling = true;
      if (userScrollTimeout) clearTimeout(userScrollTimeout);
      userScrollTimeout = setTimeout(() => {
        isUserScrolling = false;
      }, 1600);
    };

    container.addEventListener('touchstart', onUserTouch, { passive: true });
    container.addEventListener('wheel', onUserTouch, { passive: true });
    container.addEventListener('mousedown', onUserTouch, { passive: true });
  }

  /**
   * Implementa un scroll automático suave que mantenga centrada la línea activa en la vista
   * sin brincos bruscos, verificando umbrales de tolerancia y evitando colisiones con el usuario.
   */
  function smoothScrollToCenter(container, activeElement, options = {}) {
    if (!container || !activeElement) return;

    // Si el usuario está tocando o desplazando manualmente, respetar su lectura y no interrumpir
    if (isUserScrolling && !options.force) return;

    const containerHeight = container.clientHeight;
    const elementHeight = activeElement.offsetHeight || 50;
    const elementTop = activeElement.offsetTop || 0;

    // Posición calculada para alinear exactamente el centro del elemento con el centro visible
    const targetScrollTop = Math.max(0, elementTop - (containerHeight / 2) + (elementHeight / 2));
    const currentScrollTop = container.scrollTop;

    // Umbral de tolerancia: si ya está centrado (+/- 16px), omitir el desplazamiento para evitar vibraciones
    const distanceDelta = Math.abs(currentScrollTop - targetScrollTop);
    if (distanceDelta < 16 && !options.force) {
      return;
    }

    try {
      container.scrollTo({
        top: targetScrollTop,
        behavior: 'smooth'
      });
    } catch (e) {
      // Fallback para navegadores antiguos sin smooth behavior
      container.scrollTop = targetScrollTop;
    }
  }

  function findLineIndexByTime(currentTime, lines) {
    if (!lines || lines.length === 0) return 0;
    let matched = 0;
    for (let i = 0; i < lines.length; i++) {
      const lineTime = typeof lines[i].time === 'number' ? lines[i].time : 0;
      if (currentTime >= lineTime) {
        matched = i;
      } else {
        break;
      }
    }
    return matched;
  }

  function updateVisualHighlight(index) {
    const container = getContainer();
    if (!container) return;

    const rows = container.querySelectorAll('.music-stanza-row, [id^="storyParagraphCard-"], .karaoke-sync-row');
    rows.forEach((row, rIdx) => {
      if (rIdx === index) {
        row.classList.add('active-sync-line', 'ring-2', 'ring-cyan-400', 'shadow-[0_0_25px_rgba(6,182,212,0.45)]', 'scale-[1.02]');
        row.classList.remove('opacity-60');
        smoothScrollToCenter(container, row);
      } else {
        row.classList.remove('active-sync-line', 'ring-2', 'ring-cyan-400', 'shadow-[0_0_25px_rgba(6,182,212,0.45)]', 'scale-[1.02]');
        if (rows.length > 3) {
          row.classList.add('opacity-90');
        }
      }
    });

    const badge = document.getElementById('karaokeTimeBadge');
    if (badge && rows.length > 0) {
      badge.textContent = 'Estrofa ' + (index + 1) + ' de ' + rows.length;
    }
  }

  function onAudioTimeUpdate(currentTime, duration) {
    if (!isSyncActive) return;
    const lines = activeTrackData ? (activeTrackData.lyrics || activeTrackData.paragraphs) : null;
    if (!lines || lines.length === 0) return;

    const newIndex = findLineIndexByTime(currentTime, lines);
    if (newIndex !== currentActiveIndex) {
      currentActiveIndex = newIndex;
      updateVisualHighlight(newIndex);
      notifySubscribers('linechange', {
        index: newIndex,
        line: lines[newIndex],
        currentTime: currentTime,
        duration: duration || 0
      });
    }

    notifySubscribers('timeupdate', {
      currentTime: currentTime,
      duration: duration || 0,
      activeIndex: currentActiveIndex
    });
  }

  function notifySubscribers(event, data) {
    subscribers.forEach(fn => {
      try { fn(event, data); } catch (err) { console.warn('Sync subscriber error:', err); }
    });
  }

  return {
    /**
     * Vincula un reproductor de audio HTML5 (<audio>) escuchando directamente su evento 'timeupdate'
     */
    attachAudioPlayer: function(audioEl, trackData) {
      if (!audioEl) return;
      attachedPlayer = audioEl;
      if (trackData) activeTrackData = trackData;
      isSyncActive = true;

      const container = getContainer();
      if (container) monitorUserScrollInteractions(container);

      audioEl.removeEventListener('timeupdate', audioEl._karaokeTimeUpdateHandler);
      audioEl._karaokeTimeUpdateHandler = function() {
        onAudioTimeUpdate(audioEl.currentTime, audioEl.duration);
      };
      audioEl.addEventListener('timeupdate', audioEl._karaokeTimeUpdateHandler);

      audioEl.addEventListener('play', () => { isSyncActive = true; });
      audioEl.addEventListener('pause', () => { isSyncActive = false; });
      audioEl.addEventListener('seeked', () => {
        onAudioTimeUpdate(audioEl.currentTime, audioEl.duration);
      });
    },

    /**
     * Permite a YouTube IFrame API o Web Speech API despachar eventos 'timeupdate'
     * estandarizados al motor de sincronización unificado.
     */
    dispatchTimeUpdate: function(currentTime, duration = 0) {
      isSyncActive = true;
      const container = getContainer();
      if (container) monitorUserScrollInteractions(container);
      onAudioTimeUpdate(currentTime, duration);
    },

    setTrackData: function(data) {
      activeTrackData = data;
      currentActiveIndex = -1;
    },

    setContainer: function(containerEl) {
      activeLyricsContainer = containerEl;
      if (containerEl) monitorUserScrollInteractions(containerEl);
    },

    scrollToCenter: function(activeElement, options) {
      const container = getContainer();
      if (container && activeElement) {
        smoothScrollToCenter(container, activeElement, options);
      }
    },

    subscribe: function(callback) {
      if (typeof callback === 'function') subscribers.push(callback);
    },

    stop: function() {
      isSyncActive = false;
    },

    start: function() {
      isSyncActive = true;
    },

    getCurrentIndex: function() {
      return currentActiveIndex;
    }
  };
})();

