window.VOCAB_ENGINE = (function() {
  const modules = window.MASTER_MODULES_DATA;
  const indexByModule = {};
  for (const modKey in modules) {
    const items = modules[modKey].items;
    indexByModule[modKey] = {
      items: items,
      byLetter: {},
      searchTokens: items.map((item, idx) => ({
        idx: idx,
        termLower: item.term.toLowerCase(),
        meaningLower: (item.meaning || '').toLowerCase(),
        exampleLower: (item.example || '').toLowerCase(),
        pronLower: (item.pron || '').toLowerCase()
      }))
    };
    items.forEach((item, idx) => {
      const letKey = (item.letter || item.term[0] || 'A').toUpperCase();
      if (!indexByModule[modKey].byLetter[letKey]) {
        indexByModule[modKey].byLetter[letKey] = [];
      }
      indexByModule[modKey].byLetter[letKey].push(idx);
    });
  }
  return {
    getModuleItems: function(modKey) {
      return (modules[modKey] && modules[modKey].items) || [];
    },
    getModuleTitle: function(modKey) {
      return (modules[modKey] && modules[modKey].title) || modKey;
    },
    getItemsByLetter: function(modKey, letter) {
      const idxObj = indexByModule[modKey];
      if (!idxObj) return [];
      const indices = idxObj.byLetter[letter.toUpperCase()] || [];
      return indices.map(i => idxObj.items[i]);
    },
    getAvailableLetters: function(modKey) {
      const idxObj = indexByModule[modKey];
      if (!idxObj) return [];
      return Object.keys(idxObj.byLetter).sort();
    },
    searchInstant: function(modKey, query) {
      const idxObj = indexByModule[modKey];
      if (!idxObj) return [];
      if (!query || !query.trim()) return idxObj.items;
      const q = query.trim().toLowerCase();
      const results = [];
      const tokens = idxObj.searchTokens;
      const items = idxObj.items;
      for (let i = 0; i < tokens.length; i++) {
        const t = tokens[i];
        if (t.termLower.startsWith(q)) {
          results.unshift(items[t.idx]);
        } else if (t.termLower.includes(q) || t.meaningLower.includes(q) || t.exampleLower.includes(q)) {
          results.push(items[t.idx]);
        }
      }
      return results;
    }
  };
})();
